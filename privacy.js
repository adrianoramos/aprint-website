const policyLanguageSelect = document.querySelector("#policy-language");

function choosePolicyLanguage() {
  const savedLanguage = localStorage.getItem("aprint-site-language");
  if (Object.hasOwn(policyTranslations, savedLanguage)) return savedLanguage;

  const browserLanguage = navigator.language.toLowerCase().split("-")[0];
  if (browserLanguage === "pt") return "pt-BR";
  if (browserLanguage === "es") return "es";
  return "en";
}

function setPolicyLanguage(language) {
  const selected = Object.hasOwn(policyTranslations, language) ? language : "en";
  const strings = policyTranslations[selected];
  document.documentElement.lang = selected;

  document.querySelectorAll("[data-policy-i18n]").forEach((element) => {
    element.textContent = strings[element.dataset.policyI18n];
  });
  document.querySelectorAll("[data-policy-aria]").forEach((element) => {
    element.setAttribute("aria-label", strings[element.dataset.policyAria]);
  });

  document.title = strings.pageTitle;
  document.querySelector('meta[name="description"]').content = strings.description;
  policyLanguageSelect.value = selected;
}

policyLanguageSelect.addEventListener("change", () => {
  setPolicyLanguage(policyLanguageSelect.value);
  localStorage.setItem("aprint-site-language", policyLanguageSelect.value);
});
setPolicyLanguage(choosePolicyLanguage());
